"""Writes src/catalog.rs from Mozilla's model registry.

Every file is pinned by the sha256 of its unpacked content. The registry gives that for
models only, so vocabularies and shortlists are downloaded once here to hash them.

    python3 crates/provider-bergamot/catalog.py
"""

import gzip, hashlib, json, os, urllib.request

BASE = "https://storage.googleapis.com/moz-fx-translations-data--303e-prod-translations-data"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "catalog.rs")
# Released for desktop; "Release Android" models are smaller copies of desktop ones.
RELEASED = ("Release", "Release Desktop")
# A registry code with no BCP 47 tag that recognizers use.
SKIP = {"hbs"}


def get(path):
    with urllib.request.urlopen(f"{BASE}/{path}") as r:
        return r.read()


def size(path):
    req = urllib.request.Request(f"{BASE}/{path}", method="HEAD")
    with urllib.request.urlopen(req) as r:
        return int(r.headers["Content-Length"])


def file(entry, sha256=None):
    path = entry["path"]
    if sha256 is None:
        sha256 = hashlib.sha256(gzip.decompress(get(path))).hexdigest()
    return f'File {{ path: "{path}", bytes: {size(path)}, sha256: "{sha256}" }}'


def main():
    models = json.loads(get("db/models.json"))["models"]
    rows = []
    for pair in sorted(models):
        released = [m for m in models[pair] if m["releaseStatus"] in RELEASED]
        if not released:
            continue
        m = min(released, key=lambda m: m["releaseStatus"] != "Release Desktop")
        source, target = m["sourceLanguage"], m["targetLanguage"]
        if source in SKIP or target in SKIP:
            continue
        f = m["files"]
        vocab = f.get("vocab") or f["srcVocab"]
        trg = f'Some({file(f["trgVocab"])})' if "trgVocab" in f else "None"
        rows.append(
            f'    Direction {{\n        from: "{source}",\n        to: "{target}",\n'
            f'        model: {file(f["model"], f["model"]["uncompressedHash"])},\n'
            f"        src_vocab: {file(vocab)},\n        trg_vocab: {trg},\n"
            f'        shortlist: {file(f["lexicalShortlist"])},\n    }},'
        )
        print(pair, m["architecture"], m["releaseStatus"], flush=True)
    with open(OUT, "w", newline="\n") as out:
        out.write(
            "//! Generated by `catalog.py` from Mozilla's model registry. Do not edit.\n\n"
            "use crate::{Direction, File};\n\n"
            f'pub const BASE: &str = "{BASE}";\n\n'
            "pub const ALL: &[Direction] = &[\n" + "\n".join(rows) + "\n];\n"
        )


main()
